#!/usr/bin/env node
// Compiles the contracts in contracts/ into standalone JavaScript validators.
//
// The Worker cannot compile schemas at runtime: Cloudflare Workers refuse
// dynamic code generation, and Ajv builds its validators with `new Function`.
// Generating them ahead of time keeps one source of truth for the browser,
// the Worker, and the Python fixture tests.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import Ajv2020, { _ } from 'ajv/dist/2020.js'
import addFormats from 'ajv-formats'
import standaloneCode from 'ajv/dist/standalone/index.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

export const CONTRACT_SOURCES = {
  envelope: 'events/v1/envelope.schema.json',
  consent: 'privacy/v1/consent.schema.json',
  privacy_consent_changed: 'events/v1/payloads/privacy-consent-changed.schema.json',
  highlight_created: 'events/v1/payloads/highlight-created.schema.json',
  highlight_updated: 'events/v1/payloads/highlight-updated.schema.json',
  highlight_deleted: 'events/v1/payloads/highlight-deleted.schema.json',
  conversation_started: 'events/v1/payloads/conversation-started.schema.json',
  question_asked: 'events/v1/payloads/question-asked.schema.json',
  book_opened: 'events/v1/payloads/book-opened.schema.json',
  book_closed: 'events/v1/payloads/book-closed.schema.json',
  reading_progressed: 'events/v1/payloads/reading-progressed.schema.json',
  chapter_entered: 'events/v1/payloads/chapter-entered.schema.json',
  book_completed: 'events/v1/payloads/book-completed.schema.json',
  book_reopened: 'events/v1/payloads/book-reopened.schema.json',
}

const HEADER = `// Generated by tools/generate-event-validators.mjs. Do not edit.
// Run \`npm run contracts:validators\` after changing anything in contracts/.
import * as ajvFormats from 'ajv-formats/dist/formats.js'

const formats = ajvFormats.fullFormats ?? ajvFormats.default.fullFormats
`

export function generateValidatorSource() {
  const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    strictRequired: false,
    code: { source: true, esm: true, formats: _`formats` },
  })
  addFormats(ajv)

  for (const [name, file] of Object.entries(CONTRACT_SOURCES)) {
    ajv.addSchema(JSON.parse(readFileSync(join(root, 'contracts', file), 'utf8')), name)
  }

  const exports = Object.fromEntries(
    Object.keys(CONTRACT_SOURCES).map((name) => [`validate_${name}`, name]),
  )
  return `${HEADER}\n${standaloneCode(ajv, exports)}`
}

const OUTPUT = join(root, 'shared/events/validators.generated.js')

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, generateValidatorSource())
  console.log(`wrote ${OUTPUT}`)
}
