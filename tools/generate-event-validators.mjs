#!/usr/bin/env node
// Compiles the contracts in contracts/ into standalone JavaScript validators.
//
// The Worker cannot compile schemas at runtime: Cloudflare Workers refuse
// dynamic code generation, and Ajv builds its validators with `new Function`.
// Generating them ahead of time keeps one source of truth for the browser,
// the Worker, and the Python fixture tests.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import Ajv2020, { _ } from 'ajv/dist/2020.js'
import addFormats from 'ajv-formats'
import standaloneCode from 'ajv/dist/standalone/index.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

const PAYLOAD_MANIFEST = JSON.parse(
  readFileSync(join(root, 'contracts/events/v1/payloads.json'), 'utf8'),
).payloads

// Derived from the manifest rather than retyped. Three registries used to list
// these by hand and two of them drifted.
export const CONTRACT_SOURCES = {
  envelope: 'events/v1/envelope.schema.json',
  consent: 'privacy/v1/consent.schema.json',
  ...Object.fromEntries(
    Object.entries(PAYLOAD_MANIFEST).map(([type, file]) => [
      type,
      `events/v1/payloads/${file}`,
    ]),
  ),
}

const HEADER = `// Generated by tools/generate-event-validators.mjs. Do not edit.
// Run \`npm run contracts:validators\` after changing anything in contracts/.
import * as ajvFormats from 'ajv-formats/dist/formats.js'

const formats = ajvFormats.fullFormats ?? ajvFormats.default.fullFormats
`

export function generateValidatorSource() {
  const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    strictRequired: false,
    code: { source: true, esm: true, formats: _`formats` },
  })
  addFormats(ajv)

  for (const [name, file] of Object.entries(CONTRACT_SOURCES)) {
    ajv.addSchema(JSON.parse(readFileSync(join(root, 'contracts', file), 'utf8')), name)
  }

  const exports = Object.fromEntries(
    Object.keys(CONTRACT_SOURCES).map((name) => [`validate_${name}`, name]),
  )
  return `${HEADER}\n${standaloneCode(ajv, exports)}`
}

/**
 * The declarations are generated too. They used to be written by hand while
 * claiming to be fixed by this file, so adding a contract compiled cleanly and
 * then failed to typecheck against a declaration nobody had updated.
 */
export function generateDeclarationSource() {
  const declarations = Object.keys(CONTRACT_SOURCES)
    .map((name) => `export declare const validate_${name}: StandaloneValidator`)
    .join('\n')
  return `// Types for the generated validators. The generator emits plain JavaScript so
// the Worker can run it without dynamic code generation, so the declarations
// are generated alongside it by tools/generate-event-validators.mjs.
export interface StandaloneValidatorError {
  instancePath: string
  schemaPath: string
  keyword: string
  message?: string
  params?: Record<string, unknown>
}

export interface StandaloneValidator {
  (data: unknown): boolean
  errors?: StandaloneValidatorError[] | null
}

${declarations}
`
}

const OUTPUT = join(root, 'shared/events/validators.generated.js')
const DECLARATIONS = join(root, 'shared/events/validators.generated.d.ts')

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, generateValidatorSource())
  writeFileSync(DECLARATIONS, generateDeclarationSource())
  console.log(`wrote ${OUTPUT}`)
  console.log(`wrote ${DECLARATIONS}`)
}
